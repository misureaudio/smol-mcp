class DifferentialEvolutionMP:
    """
    Arbitrary-precision Differential Evolution.
    Strategy: DE/rand/1/bin (classic and robust).
    Now includes a highly optimized step() method for single-generation evolution.
    """
    def __init__(self,
                 objective_function,
                 bounds,
                 pop_size=50,
                 F=mp.mpf('0.8'),
                 CR=mp.mpf('0.9'),
                 strategy='rand/1/bin',
                 dps=50):
        mp.mp.dps = int(dps)
        self.func = objective_function
        self.bounds = [[mp.mpf(b[0]), mp.mpf(b[1])] for b in bounds]
        self.dim = len(self.bounds)
        self.pop_size = int(pop_size)
        self.F = F
        self.CR = CR
        self.strategy = strategy

        self.population = []
        self.fitness = []
        self.best_solution = None
        self.best_value = mp.inf

    def init_population(self):
        """Initializes or re-initializes the population. Call this once before starting."""
        self.population = []
        for _ in range(self.pop_size):
            ind = [low + (high - low) * mp.rand() for low, high in self.bounds]
            self.population.append(ind)
        self._evaluate_population()

    def _evaluate_population(self):
        """Evaluates the entire population and updates the best-known solution."""
        self.fitness = [self.func(ind) for ind in self.population]
        min_val = min(self.fitness)
        if min_val < self.best_value:
            self.best_value = min_val
            self.best_solution = list(self.population[self.fitness.index(min_val)])

    def _mutate_rand1(self, idx):
        """DE/rand/1 mutation"""
        candidates = [i for i in range(self.pop_size) if i != idx]
        a, b, c = random.sample(candidates, 3)
        return [self.population[a][k] + self.F * (self.population[b][k] - self.population[c][k])
                for k in range(self.dim)]

    def _crossover_bin(self, target, mutant):
        """Binomial crossover"""
        # ... (This method is correct as is) ...
        trial = []
        j_rand = random.randint(0, self.dim - 1)
        for j in range(self.dim):
            if j == j_rand or mp.rand() < self.CR:
                trial.append(mutant[j])
            else:
                trial.append(target[j])
        return trial

    def _clip(self, individual):
        # Use mpmath's fmax and fmin for high-precision clipping
        # return [mp.fmax(low, mp.fmin(x, high)) for x, (low, high) in zip(individual, self.bounds)]
        return [max(low, min(x, high)) for x, (low, high) in zip(individual, self.bounds)]

    def step(self):
        """
        Performs exactly ONE generation of DE with OPTIMIZED evaluations.
        This enables fine-grained control in island models.
        """
        new_pop = []
        new_fitness = []  # Build the new fitness list simultaneously

        for i in range(self.pop_size):
            target = self.population[i]
            target_fitness = self.fitness[i]

            mutant = self._mutate_rand1(i)
            trial = self._crossover_bin(target, mutant)
            trial = self._clip(trial)

            trial_val = self.func(trial)  # The only function evaluation

            if trial_val <= target_fitness:
                # The new individual wins
                new_pop.append(trial)
                new_fitness.append(trial_val)
                # Check if it's a new global best
                if trial_val < self.best_value:
                    self.best_value = trial_val
                    self.best_solution = list(trial)
            else:
                # The original individual survives
                new_pop.append(target)
                new_fitness.append(target_fitness)

        # Update the population and fitness lists in one go
        self.population = new_pop
        self.fitness = new_fitness

    def optimize(self, generations, return_history=False):
        """Runs the full optimization process."""
        self.init_population()
        history = [{'generation': 0,
                    'best_energy': self.best_value,
                    'best_solution': list(self.best_solution)}]

        for gen in range(1, int(generations) + 1):
            self.step()  # Evolve by one generation
            if return_history:
                history.append({'generation': gen,
                                'best_energy': self.best_value,
                                'best_solution': list(self.best_solution)})

        return self.best_solution, self.best_value, history if return_history else None

class IslandModelDEMP:
    """
    Island Model Differential Evolution in pure mpmath.
    Multiple independent islands with periodic migration of best individuals.
    Correctly evolves populations without re-initializing.
    """
    def __init__(self,
                 objective_function,
                 bounds,
                 num_islands=4,
                 island_pop_size=40,
                 generations=200,
                 migration_interval=20,
                 migrants_per_island=2,
                 F=mp.mpf('0.8'),
                 CR=mp.mpf('0.9'),
                 dps=50):
        mp.mp.dps = int(dps)
        self.func = objective_function
        self.bounds = bounds
        self.num_islands = num_islands
        self.island_pop_size = island_pop_size
        self.generations = generations
        self.migration_interval = migration_interval
        self.migrants_per_island = migrants_per_island

        # Note: We don't pass 'generations' to the DE instances anymore.
        self.islands = [
            DifferentialEvolutionMP(
                objective_function=objective_function,
                bounds=bounds,
                pop_size=island_pop_size,
                F=F, CR=CR, dps=dps
            ) for _ in range(num_islands)
        ]

        self.global_best_solution = None
        self.global_best_value = mp.inf
        self.history = []

    def _migrate(self):
        """Collects best individuals and sends them to other islands, replacing the worst."""
        island_bests = [(island.best_value, list(island.best_solution))
                        for island in self.islands]

        # Sort by value to find the top overall performers.
        island_bests.sort(key=lambda x: x[0])

        # Distribute the top N migrants to all other islands.
        for i in range(min(self.migrants_per_island, len(island_bests))):
            migrant_val, migrant_sol = island_bests[i]

            for target_island in self.islands:
                # Find the indices of the worst individuals in the target island.
                # Using argpartition is more efficient than a full sort.
                worst_indices = np.argpartition(target_island.fitness, -self.migrants_per_island)[-self.migrants_per_island:]

                # Replace one of the worst individuals with the migrant.
                replace_idx = random.choice(worst_indices)
                target_island.population[replace_idx] = list(migrant_sol)
                target_island.fitness[replace_idx] = migrant_val

                # Check if this migrant is the new best for this island
                if migrant_val < target_island.best_value:
                    target_island.best_value = migrant_val
                    target_island.best_solution = list(migrant_sol)

    def optimize(self):
        """Runs the full island model optimization."""
        # 1. Initialize all islands ONCE.
        for island in self.islands:
            island.init_population()

        # Update global best after initialization
        for island in self.islands:
            if island.best_value < self.global_best_value:
                self.global_best_value = island.best_value
                self.global_best_solution = list(island.best_solution)

        self.history.append({
            'generation': 0,
            'global_best_energy': self.global_best_value,
            'global_best_solution': list(self.global_best_solution)
        })

        # 2. Run the evolution loop.
        for gen in range(1, self.generations + 1):
            # Run one generation on each island.
            for island in self.islands:
                island.step()

            # Perform migration at the specified interval.
            if gen % self.migration_interval == 0:
                self._migrate()

            # Update global best from all islands.
            for island in self.islands:
                if island.best_value < self.global_best_value:
                    self.global_best_value = island.best_value
                    self.global_best_solution = list(island.best_solution)

            self.history.append({
                'generation': gen,
                'global_best_energy': self.global_best_value,
                'global_best_solution': list(self.global_best_solution)
            })

        return self.global_best_solution, self.global_best_value, self.history

